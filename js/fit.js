/* تكبير الصفحة كلها بنسبة عرض الشاشة فوق 1600px — نفس التصميم بس أكبر
   بالتناسب على الشاشات العريضة (2K/4K) بدل محتوى صغير بنص فراغ. أغلب
   المقاسات بكسل ثابت، فتكبير الخط وحده ما يكفي. تحت 1600 صفر تغيير. عرض
   التخطيط يبقى 1600، أعرض من منطقة المحتوى (1200) عمداً عشان تبقى مساحة
   فاضية على الجانبين. بالـhead عشان يطبَّق قبل أول رسم بلا قفزة. */
(function () {
  var root = document.documentElement;
  function fit() {
    root.style.zoom = Math.min(1.8, Math.max(1, window.innerWidth / 1600));
  }
  fit();
  window.addEventListener("resize", fit);
})();
